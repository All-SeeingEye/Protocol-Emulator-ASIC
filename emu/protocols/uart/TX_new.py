    # Timing
    # --------------------------------------------------
    ("LOAD_T", 0, 9),       # 10 cycles per bit total

    # --------------------------------------------------
    # TX pin setup
    # --------------------------------------------------
    ("SET", 0, 1),          # idle HIGH
    ("DIR", 0, 1),          # GPIO0 = OUTPUT

    # --------------------------------------------------
    # Start bit
    # --------------------------------------------------
    ("SET", 0, 0),
    ("WAIT_T", 0),

    # --------------------------------------------------
    # Send all 8 data bits
