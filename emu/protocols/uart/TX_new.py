    # UART is LSB first, so use R.
    # Sends exactly 8 bits. No padding.
    # --------------------------------------------------
    ("OUT_W", "R", 0, 0, 8, 0),

    # --------------------------------------------------
    # Stop bit
    # --------------------------------------------------
    ("SET", 0, 1),
    ("WAIT_T", 0),

